import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import type { Express } from "express";
import type { Pool } from "pg";
type Call=(path:string,method?:string,body?:unknown,actor?:number,key?:string)=>Promise<{status:number;body:any}>;
export async function testPositions(app:Express,pool:Pool,call:Call) {
  await pool.query(`ALTER TABLE warehouses ADD COLUMN IF NOT EXISTS name text,ADD COLUMN bins jsonb DEFAULT '[]'::jsonb;
    UPDATE warehouses SET name='Warehouse '||id;
    ALTER TABLE warehouse_inventory ADD COLUMN aisle text;
    CREATE TABLE mdm_sites(id integer PRIMARY KEY,organization_id integer,code text,name text,active boolean);
    INSERT INTO mdm_sites VALUES(1,1,'JHB','Johannesburg',true),(2,2,'JHB','Foreign site',true),(3,1,'OFF','Inactive',false);
    UPDATE warehouses SET bins='[{"code":"OLD","aisle":"Aisle 1","shelf":"Top"}]' WHERE id=1;`);
  const sql=await readFile("migrations/20260915160000_warehouse_position_foundation.sql","utf8");await pool.query(sql);await pool.query(sql);
  const {registerPositionRoutes}=await import("../server/modules/inventory-positions/register-position-routes");
  registerPositionRoutes(app,{ensureAuthenticated:(_req,_res,next)=>next(),ensurePermission:(_resource,action)=>(req,res,next)=>{if(req.get("Actor")==="4"&&action!=="read"){res.status(403).json({denied:true});return;}next();}});
  const base="/api/v2/inventory";
  let result=await call(`${base}/positions`);
  assert.equal(result.status,200,JSON.stringify(result.body));
  assert.equal(result.body.data.items.length,1);
  assert.equal(result.body.data.items[0].locationState,"unresolved");
  assert.equal(result.body.data.items[0].onHand,"97");
  assert.equal(result.body.data.capabilities.qualityHolds,false);
  assert.equal(result.body.data.capabilities.splitPositions,false);
  assert.match(result.body.data.notice,/limited planning projection, not allocation authority/);
  assert.equal(result.body.data.summary.unresolved,1);
  assert.equal((await call(`${base}/locations?kind=sites&q=Johannesburg`)).body.data.items[0].id,1);
  assert.equal((await call(`${base}/locations?kind=bins&pageSize=1000`)).status,400);
  assert.equal((await call(`${base}/locations/warehouse-site`,"POST",{warehouseId:1,siteId:2,reason:"Link site"})).status,404);
  assert.equal((await call(`${base}/locations/warehouse-site`,"POST",{warehouseId:1,siteId:3,reason:"Link site"})).status,404);
  assert.equal((await call(`${base}/locations/warehouse-site`,"POST",{warehouseId:2,siteId:2,reason:"Link site"})).status,403);
  assert.equal((await call(`${base}/locations/warehouse-site`,"POST",{warehouseId:1,siteId:1,reason:"Verified site"},4)).status,403);
  assert.equal((await call(`${base}/locations/warehouse-site`,"POST",{warehouseId:1,siteId:1,reason:"Verified site"})).status,200);
  const zone=(await call(`${base}/locations/zones`,"POST",{warehouseId:1,code:"Z1",name:"Receiving zone"})).body.data.id;
  assert.ok(zone);
  assert.equal((await call(`${base}/locations/zones`,"POST",{warehouseId:1,code:"z1",name:"Duplicate"})).status,409);
  assert.equal((await call(`${base}/locations/bins`,"POST",{warehouseId:2,zoneId:zone,code:"B1"})).status,403);
  assert.equal((await call(`${base}/locations/bins`,"POST",{warehouseId:1,zoneId:zone,code:"OLD",aisle:"Wrong aisle"})).status,409);
  const imported=(await call(`${base}/locations/bins`,"POST",{warehouseId:1,zoneId:zone,code:"OLD"})).body.data.id;
  assert.equal((await pool.query("SELECT aisle FROM wms_bins WHERE id=$1",[imported])).rows[0].aisle,"Aisle 1");
  const bin=(await call(`${base}/locations/bins`,"POST",{warehouseId:1,zoneId:zone,code:"NEW",aisle:"A2"})).body.data.id;
  assert.ok(bin);
  assert.ok((await pool.query("SELECT bins FROM warehouses WHERE id=1")).rows[0].bins.some((b:{code:string})=>b.code==="NEW"));
  const snapshot=(await call(`${base}/positions`)).body.data.items[0];
  const request={binId:bin,revision:snapshot.revision,reason:"Verified all stock physically in new bin"};
  assert.equal((await call(`${base}/positions/1/reconcile`,"POST",request,4)).status,403);
  assert.equal((await call(`${base}/positions/2/reconcile`,"POST",request)).status,404);
  assert.equal((await call(`${base}/positions/1/reconcile`,"POST",{...request,quantity:999})).status,400);
  result=await call(`${base}/positions/1/reconcile`,"POST",request);
  assert.equal(result.status,200,JSON.stringify(result.body));
  assert.equal(result.body.data.quantityChanged,false);
  assert.equal((await call(`${base}/positions/1/history`)).body.data.items[0].quantitySnapshot,"97.000000");
  assert.equal((await call(`${base}/positions/1/history`,"GET",undefined,3)).status,404);
  let position=(await call(`${base}/positions`)).body.data.items[0];
  assert.equal(position.locationState,"reconciled");assert.equal(position.binCode,"NEW");
  assert.equal((await pool.query("SELECT quantity,bin,aisle FROM warehouse_inventory WHERE id=1")).rows[0].quantity,97);
  assert.equal((await pool.query("SELECT quantity FROM inventory_items WHERE id=1")).rows[0].quantity,97);
  assert.equal((await call(`${base}/positions/1/reconcile`,"POST",request)).status,409);
  assert.equal((await call(`${base}/positions?status=reconciled`)).body.data.total,1);
  await assert.rejects(pool.query("UPDATE wms_position_reconciliations SET reason='overwrite'"),/IMMUTABLE/);
  await pool.query("UPDATE warehouse_inventory SET quantity=98 WHERE id=1");
  position=(await call(`${base}/positions`)).body.data.items[0];assert.equal(position.locationState,"unresolved");
  assert.equal((await call(`${base}/positions?status=reconciled`)).body.data.total,0);
  assert.equal((await call(`${base}/positions?status=unresolved`)).body.data.total,1);
  assert.equal((await call(`${base}/positions`,"GET",undefined,3)).body.data.items[0].itemId,2);
  // The evidence write and the legacy location update must roll back together.
  await pool.query(`CREATE FUNCTION fail_position_audit() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.action='INVENTORY_POSITION_RECONCILED' THEN RAISE EXCEPTION 'forced audit error'; END IF; RETURN NEW; END $$;
    CREATE TRIGGER fail_position_audit BEFORE INSERT ON audit_logs FOR EACH ROW EXECUTE FUNCTION fail_position_audit()`);
  result=await call(`${base}/positions/1/reconcile`,"POST",{binId:imported,revision:position.revision,reason:"Rollback test only"});
  assert.equal(result.status,500);
  assert.equal((await pool.query("SELECT bin FROM warehouse_inventory WHERE id=1")).rows[0].bin,"NEW");
  await pool.query("DROP TRIGGER fail_position_audit ON audit_logs");
  await pool.query("INSERT INTO warehouse_inventory(organization_id,warehouse_id,item_id,quantity) SELECT 1,1,1,1 FROM generate_series(1,5000)");
  for(const size of [25,50,100]){const data=(await call(`${base}/positions?page=2&pageSize=${size}`)).body.data;assert.equal(data.items.length,size);assert.equal(data.total,5001);}
  console.log("Position runtime checks passed: canonical locations, legacy-bin compatibility, unchanged quantities, immutable evidence, stale revisions, isolation, rollback and 5,000-row pagination.");
}

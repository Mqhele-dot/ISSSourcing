import assert from "node:assert/strict";
import { buildDatedReportingEvidence } from "../server/lib/dated-reporting-evidence";
import { parseReportingDecimal, formatReportingDecimal } from "../server/lib/exact-reporting-decimal";
import type { ApprovedReportingRate, FinancialContribution } from "../shared/financial-measures";

const source: FinancialContribution = { sourceType:"purchase_order",sourceId:"1",sourceRevision:"1",date:"2026-01-10T12:00:00Z",amount:"100.10",currencyCode:"USD" };
const rate: ApprovedReportingRate = {id:"1",version:1,organizationId:1,fromCurrencyCode:"USD",toCurrencyCode:"ZAR",rate:"18.5",effectiveAt:"2026-01-01T00:00:00Z",expiresAt:null,approvedAt:"2026-01-01T00:00:00Z",supersededAt:null};
const run = (contributions: FinancialContribution[], rates: ApprovedReportingRate[] = [rate], currencyCode: string|null = "ZAR", generatedAt = "2026-02-01T00:00:00Z") => buildDatedReportingEvidence({organizationId:1,currencyCode,decimalPlaces:2,generatedAt,contributions,rates});
assert.equal(run([source]).amount,"1851.85");
assert.equal(run([]).state,"empty");
assert.equal(run([]).amount,"0.00");
assert.equal(run([source],[],null).state,"setup_required");
assert.equal(run([source],[]).amount,null);
assert.equal(run([source],[]).state,"unavailable");
assert.equal(run([source],[{...rate,organizationId:2}]).state,"unavailable");
assert.equal(run([source],[{...rate,effectiveAt:"2026-01-11T00:00:00Z"}]).state,"unavailable");
assert.equal(run([source],[{...rate,expiresAt:source.date}]).state,"unavailable");
assert.equal(run([source],[{...rate,fromCurrencyCode:"ZAR",toCurrencyCode:"USD"}]).state,"unavailable");
const partial = run([source,{...source,sourceId:"2",currencyCode:"EUR"}]);
assert.equal(partial.state,"partial");
assert.equal(partial.amount,"1851.85");
assert.deepEqual(partial.excludedOriginalAmounts,[{currencyCode:"EUR",amount:"100.10"}]);
assert.equal(run([{...source,currencyCode:"ZAR"}],[]).amount,"100.10");
assert.equal(run([{...source,date:null}]).evidence[0].exclusion,"missing_date");
assert.equal(run([{...source,amount:"NaN"}]).evidence[0].exclusion,"invalid_amount");
assert.equal(run([{...source,exclusion:"missing_price_evidence"}]).state,"unavailable");
assert.equal(run([{...source,amount:"-100.10"}]).amount,"-1851.85");
assert.equal(formatReportingDecimal(parseReportingDecimal("-1.005"),2),"-1.01");
assert.equal(formatReportingDecimal(parseReportingDecimal("9007199254740993.01"),2),"9007199254740993.01");
const corrected = [{...rate,supersededAt:"2026-03-01T00:00:00Z"},{...rate,id:"2",version:2,rate:"19",approvedAt:"2026-03-01T00:00:00Z"}];
assert.equal(run([source],corrected).amount,"1851.85");
assert.equal(run([source],corrected,"ZAR","2026-04-01T00:00:00Z").amount,"1901.90");
assert.equal(run([source, {...source,sourceId:"2",amount:"-100.10"}]).amount,"0.00");
console.log("Dated reporting evidence checks passed.");

import fs from "node:fs";
import path from "node:path";
import { buildAudit, ROOT } from "./logic-audit-lib.mjs";

const audit = buildAudit();
const artifactPath = path.join(ROOT, "artifacts", "cross-app-logic-audit.json");
const docsDir = path.join(ROOT, "docs", "audits");
fs.mkdirSync(path.dirname(artifactPath), { recursive: true });
fs.mkdirSync(docsDir, { recursive: true });
fs.writeFileSync(artifactPath, `${JSON.stringify(audit, null, 2)}\n`);

const findingMarkdown = audit.findings.map((finding) => `## ${finding.id} — ${finding.severity.toUpperCase()} — ${finding.classification}

- Capability: \`${finding.capability}\`
- Entry points: ${finding.entryPoints.join(" ↔ ")}
- Files and lines: ${finding.locations.map((location) => `\`${location}\``).join(", ")}
- Routes: ${finding.routes.map((route) => `\`${route}\``).join(", ")}
- Permissions: ${finding.permissions.join("; ")}
- Services: ${finding.services.join(", ")}
- Tables: ${finding.tables.join(", ")}
- Expected rule: ${finding.expectedRule}
- Actual behaviour: ${finding.actualBehavior}
- Why this does not/may make sense: ${finding.rationale}
- Impact: ${finding.impact}
- Reproduction: ${finding.reproduction.join(" → ")}
- Test evidence: ${finding.testEvidence.join("; ")}
- Canonical path: ${finding.canonicalPath}
- Retain/restrict/redirect/deprecate/remove: ${finding.disposition}
`).join("\n");

fs.writeFileSync(path.join(docsDir, "cross-app-logic-audit.md"), `# Cross-App Logic and Connection Audit — Wave 7C

Generated by \`npm run audit:logic-connections\` using the TypeScript AST for Express route and client endpoint discovery. The JSON artifact is the complete machine-readable inventory.

## Release decision

**${audit.releaseStatus}.** ${audit.summary.critical} critical and ${audit.summary.high} high contradictions remain. Resolved controls and retained compatibility paths are documented below.

## Coverage

- ${audit.summary.uiRoutes} visible UI routes
- ${audit.summary.serverRoutes} server routes (${audit.summary.mutatingRoutes} mutations)
- ${audit.summary.clientConnections} client endpoint references
- ${audit.summary.schemaTables} PostgreSQL tables
- ${audit.summary.findings} classified findings

False positives are explicitly classified as \`harmless alias\` or \`intentional shared path\`; confirmed problems are \`conflicting\` or \`security bypass\`.

## Evidence boundary

The AST inventory and contract-model tests prove route discovery, duplicate-path middleware structure, documented contradictions, and shared report/export construction. \`npm run test:cross-path-invariants\` additionally starts an isolated app and runs AP, sourcing, tenant-isolation, permission, audit, idempotency, and report/export proof against a reachable \`TEST_DATABASE_URL\` whose database name is explicitly disposable.

- Latest runtime proof: ${audit.runtimeEvidence.passed ? `passed at ${audit.runtimeEvidence.completedAt} on disposable database \`${audit.runtimeEvidence.database}\`` : `not available (${audit.runtimeEvidence.reason})`}
- Runtime proof complements the static control inventory; release status is blocked only when critical or high contradictions remain.

${findingMarkdown}
`);

const capabilityRows = audit.capabilityMap.map((group) => {
  const sample = group.entryPoints.slice(0, 6).map((route) => `${route.method} ${route.route} (${route.file}:${route.line})`).join("<br>");
  const middleware = [...new Set(group.entryPoints.flatMap((route) => route.middleware))].join(", ") || "none detected";
  const validators = [...new Set(group.entryPoints.flatMap((route) => route.validator))].join(", ") || "none detected";
  const services = [...new Set(group.entryPoints.flatMap((route) => route.services))].join(", ") || "inline/unknown";
  const tables = [...new Set(group.entryPoints.flatMap((route) => route.tables))].join(", ") || "indirect/unknown";
  const clients = group.clientEntryPoints.slice(0, 6).map((entry) => `${entry.file}:${entry.line}${entry.mutation ? " mutation" : " query"}${entry.invalidates ? " + invalidation" : ""}`).join("<br>") || "no literal client call detected";
  return `| \`${group.capability}\` | ${sample} | ${clients} | ${middleware} | ${validators} | ${services} | ${tables} |`;
}).join("\n");

fs.writeFileSync(path.join(docsDir, "capability-map.md"), `# Capability Map — Wave 7C

This map is generated from the TypeScript AST. Each route record in \`artifacts/cross-app-logic-audit.json\` also includes status changes, audit evidence, cache invalidation, transaction, and idempotency signals. Client references and UI routes are included there for the complete page → action → API connection inventory.

| Normalized capability | API entry points (sample) | Client query/mutation entry points | Middleware / permission | Validator | Service | Tables |
|---|---|---|---|---|---|---|
${capabilityRows}
`);

console.log(`Logic connection audit: ${audit.summary.serverRoutes} routes, ${audit.summary.clientConnections} client connections, ${audit.summary.findings} findings.`);
console.log(`Release status: ${audit.releaseStatus} (${audit.summary.critical} critical, ${audit.summary.high} high).`);

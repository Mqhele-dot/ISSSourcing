import assert from "node:assert/strict";
import type { Express } from "express";
import type { Pool } from "pg";
type Call=(path:string,method?:string,body?:unknown,actor?:number)=>Promise<{status:number;body:any}>;
export async function testInspectionRules(app:Express,pool:Pool,call:Call) {
  await pool.query("CREATE TABLE suppliers(id integer PRIMARY KEY,organization_id integer); INSERT INTO suppliers VALUES(1,1),(2,2)");
  const {registerInspectionRuleRoutes}=await import("../server/modules/inventory-positions/register-inspection-rule-routes");
  registerInspectionRuleRoutes(app,{ensureAuthenticated:(_req,_res,next)=>next(),ensurePermission:(_resource,action)=>(req,res,next)=>{if(req.get('Actor')==='4'&&action!=='read'){res.status(403).json({denied:true});return;}next();}});
  const path='/api/v2/inventory/inspection-rules/item/90001';
  assert.equal((await call(path,'GET',undefined,3)).status,404);
  const current=(await call(path)).body.data;
  const body={required:false,revision:current.revision,reason:'Policy updated after quality review'};
  assert.equal((await call(path,'PUT',body,4)).status,403);
  assert.equal((await call(path,'PUT',{...body,revision:0})).status,409);
  const saved=await call(path,'PUT',body);
  assert.equal(saved.status,200);
  assert.equal(saved.body.data.revision,current.revision+1);
  assert.equal((await call(path,'PUT',body)).status,409);
  assert.equal((await call('/api/v2/inventory/inspection-rules/supplier/2')).status,404);
  assert.equal((await call(path,'PUT',{...body,revision:saved.body.data.revision,reason:'x'})).status,400);
  await pool.query(`CREATE FUNCTION fail_inspection_rule_audit() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.action='INSPECTION_RULE_CHANGED' THEN RAISE EXCEPTION 'forced policy failure'; END IF; RETURN NEW; END $$; CREATE TRIGGER fail_inspection_rule_audit BEFORE INSERT ON audit_logs FOR EACH ROW EXECUTE FUNCTION fail_inspection_rule_audit()`);
  assert.equal((await call(path,'PUT',{...body,required:true,revision:saved.body.data.revision})).status,500);
  assert.equal((await call(path)).body.data.required,false);
  await pool.query('DROP TRIGGER fail_inspection_rule_audit ON audit_logs');
  const holds=await pool.query("SELECT hold_id FROM receipt_inspection_evidence ORDER BY receipt_item_id");
  const holdPath=`/api/v2/inventory/items/90001/safety-holds/${holds.rows[0].hold_id}/release`;
  assert.equal((await call(holdPath,'POST',{reason:'Inspection passed with documented check'},1)).status,403);
  assert.equal((await call(holdPath,'POST',{reason:'Inspection passed with documented check'},2)).status,200);
  assert.equal((await pool.query('SELECT safety_hold FROM inventory_items WHERE id=90001')).rows[0].safety_hold,true,'Other inspection remains active');
  const outstanding=await pool.query(`SELECT count(*)::int n FROM receipt_inspection_evidence ie WHERE NOT EXISTS(SELECT 1 FROM inventory_safety_releases r WHERE r.hold_id=ie.hold_id)`);
  assert.equal(outstanding.rows[0].n,1);
  await pool.query("UPDATE inventory_inspection_rules SET required=true WHERE organization_id=1 AND subject_type='supplier'");
  const {executeStockCommand}=await import("../server/modules/inventory/stock-command-service");
  const {randomUUID}=await import("node:crypto");
  await assert.rejects(executeStockCommand(1,1,randomUUID(),'RECEIPT',{itemId:90001,warehouseId:1,quantity:1}),/STOCK_INSPECTION_RECEIPT_REQUIRED/);
  await assert.rejects(pool.query('SELECT assert_unlinked_receipt_inspection(1,1)'),/STOCK_INSPECTION_RECEIPT_REQUIRED/,'Unknown supplier provenance cannot bypass policy');
  await pool.query('SELECT assert_unlinked_receipt_inspection(2,2)');
  console.log('Inspection rule API passed: tenant/permission denial, stale revisions, audit rollback and independent receipt clearance.');
}

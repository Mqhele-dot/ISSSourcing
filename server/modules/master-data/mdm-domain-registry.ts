export type MdmRiskLevel = "low" | "medium" | "high" | "critical";

export type MdmDomainRegistryEntry = {
  key: string;
  displayName: string;
  ownerRole: string;
  stewardRole: string;
  riskLevel: MdmRiskLevel;
  requiredPermissions: string[];
  requiredFields: string[];
  uniqueKeys: string[];
  highRiskFields: string[];
  approvalRequiredFields: string[];
  whereUsedChecks: string[];
  supportedActions: Array<"read" | "create" | "update" | "deactivate" | "archive" | "import" | "export" | "approve">;
  importExportSupport: "none" | "export" | "import_export";
  auditRequired: boolean;
};

const baseActions: MdmDomainRegistryEntry["supportedActions"] = [
  "read",
  "create",
  "update",
  "deactivate",
  "archive",
  "export",
];


export function getMdmDomainRegistry() {
  return MDM_DOMAIN_REGISTRY;
}

export function getMdmDomainRegistryEntry(key: string) {
  return MDM_DOMAIN_REGISTRY.find((entry) => entry.key === key);
}

export function isHighRiskMdmField(domainKey: string, fieldName: string) {
  const entry = getMdmDomainRegistryEntry(domainKey);
  return Boolean(entry?.highRiskFields.includes(fieldName) || entry?.approvalRequiredFields.includes(fieldName));
}
